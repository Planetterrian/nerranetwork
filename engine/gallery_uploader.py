# Public API
# ---------------------------------------------------------------------------


def upload_image(
    image_bytes: bytes,
    metadata: ImageMetadata,
    *,
    gallery_config: Optional[GalleryConfig] = None,
) -> Optional[UploadResult]:
    """Upload one image (original + thumbnail + sidecar) to R2.

    Returns ``None`` (and logs) when gallery credentials are missing or
    when the R2 upload of any of the three objects fails. The caller
    must treat ``None`` as a soft failure that doesn't block the
    surrounding pipeline.

    Mutates ``metadata`` in place to fill in fields the caller may have
    left blank: ``image_id`` (content hash), ``width`` / ``height`` /
    ``format`` (probed from the bytes), ``file_size``, ``generated_at``
    (UTC, RFC 3339). All caller-supplied non-empty values are
    preserved.
    """
    config = gallery_config or gallery_config_from_env()
    if not config.is_configured:
        logger.info("Gallery R2 not configured — skipping upload")
        return None

    if not image_bytes:
        logger.warning("upload_image called with empty bytes — skipping")
        return None

    try:
        width, height, probed_format = probe_image(image_bytes)
    except Exception as exc:  # noqa: BLE001 — corrupt bytes = soft fail
        logger.warning("Pillow failed to probe image bytes: %s", exc)
        return None

    if not metadata.image_id:
        metadata.image_id = compute_image_id(image_bytes)
    if not metadata.width:
        metadata.width = width
    if not metadata.height:
        metadata.height = height
    if not metadata.format:
        metadata.format = probed_format
    if not metadata.file_size:
        metadata.file_size = len(image_bytes)
    if not metadata.generated_at:
        metadata.generated_at = datetime.now(timezone.utc).isoformat(
            timespec="seconds"
        )
    if not metadata.license:
        metadata.license = LICENSE_DEFAULT
    if not metadata.license_url:
        metadata.license_url = LICENSE_URL_DEFAULT
    if not metadata.attribution:
        metadata.attribution = ATTRIBUTION_DEFAULT

    ext = _ext_for_format(metadata.format)
    original_key, thumbnail_key, sidecar_key = _build_keys(metadata, ext)

    try:
        thumbnail_bytes = make_thumbnail(image_bytes)
    except Exception as exc:  # noqa: BLE001 — thumbnail failure shouldn't block original
        logger.warning(
            "Thumbnail generation failed for image %s: %s — skipping upload",
            metadata.image_id, exc,
        )
        return None

    sidecar_bytes = metadata.to_json().encode("utf-8")

    with tempfile.TemporaryDirectory(prefix="gallery_upload_") as tmpdir:
        tmp_root = Path(tmpdir)
        original_path = tmp_root / f"{metadata.image_id}.{ext}"
        thumbnail_path = tmp_root / f"{metadata.image_id}.thumb.webp"
        sidecar_path = tmp_root / f"{metadata.image_id}.json"

        original_path.write_bytes(image_bytes)
        thumbnail_path.write_bytes(thumbnail_bytes)
        sidecar_path.write_bytes(sidecar_bytes)

        try:
            original_url = upload_to_r2(
                original_path,
                original_key,
                bucket=config.bucket,
                endpoint_url=config.endpoint_url,
                access_key=config.access_key,
                secret_key=config.secret_key,
                public_base_url=config.public_base_url,
                content_type=_content_type_for(ext),
            )
            thumbnail_url = upload_to_r2(
                thumbnail_path,
                thumbnail_key,
                bucket=config.bucket,
                endpoint_url=config.endpoint_url,
                access_key=config.access_key,
                secret_key=config.secret_key,
                public_base_url=config.public_base_url,
                content_type="image/webp",
            )
            sidecar_url = upload_to_r2(
                sidecar_path,
                sidecar_key,
                bucket=config.bucket,
                endpoint_url=config.endpoint_url,
                access_key=config.access_key,
                secret_key=config.secret_key,
                public_base_url=config.public_base_url,
                content_type="application/json",
            )
        except Exception as exc:  # noqa: BLE001 — log + soft-fail
            logger.error(
                "Gallery R2 upload failed for image %s (%s): %s",
                metadata.image_id, type(exc).__name__, exc,
            )
            return None

    return UploadResult(
        image_id=metadata.image_id,
        original_url=original_url,
        thumbnail_url=thumbnail_url,
        sidecar_url=sidecar_url,
        original_key=original_key,
        thumbnail_key=thumbnail_key,
        sidecar_key=sidecar_key,
    )
